"""Guest web router — serves the browser join page for guests without an account."""
import os

from fastapi import APIRouter, HTTPException, Request
from fastapi.responses import FileResponse, Response

from src.services import voice_languages as voice_languages_service

router = APIRouter(tags=["guest"])

_WEB_DIR = os.path.normpath(
    os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "web")
)


# These pages change with every deployment and talk to an API that changes with them, so a
# browser holding yesterday's HTML against today's API produces failures that look like
# application bugs and are not — we spent a diagnosis on exactly that.
#
# no-cache means "revalidate before use", not "do not keep". Paired with the ETag below it gives
# both halves: the browser always asks, and the answer is 304 with no body whenever nothing has
# changed. Without the conditional handling it was the worst of both — a full 64 KB download on
# every single load, because FileResponse sends an ETag and has no access to the request to
# compare it against.
_NO_CACHE = {"Cache-Control": "no-cache, must-revalidate"}


def _page(request: Request, filename: str) -> Response:
    """Serve one of the front-end pages, answering 304 when the browser already has it.

    Starlette's FileResponse computes an ETag from the file's size and modification time and
    sends it, but never reads If-None-Match — it is constructed without a request. StaticFiles
    does that comparison; a bare FileResponse cannot. So it is done here.

    Weak comparison is not needed: the tag is generated by the same code on both sides of the
    exchange and never transformed by a proxy in between, so the strings match or the file
    changed. If-Modified-Since is deliberately not consulted either — a second's resolution is
    too coarse for a page redeployed several times in a minute, which is exactly what happened
    all through the day this was written.
    """
    path = os.path.join(_WEB_DIR, filename)
    # stat_result is passed so the validators exist now rather than during the send. Without it
    # FileResponse computes the ETag lazily, in __call__, and reading response.headers here
    # returns None — the comparison below then never matched and every request answered 200.
    response = FileResponse(
        path, media_type="text/html", headers=_NO_CACHE, stat_result=os.stat(path)
    )

    known = request.headers.get("if-none-match")
    current = response.headers.get("etag")
    if known and current and known.strip() == current:
        # 304 carries no body by definition. The validators go with it so a browser that keeps
        # the response can revalidate again next time.
        return Response(
            status_code=304,
            headers={
                "ETag": current,
                "Last-Modified": response.headers.get("last-modified", ""),
                **_NO_CACHE,
            },
        )
    return response


@router.get("/join/{join_token}", include_in_schema=False)
def guest_join_page(request: Request, join_token: str):
    """Serve the browser join page. Token validation happens client-side via the API."""
    return _page(request, "join.html")


@router.get("/host", include_in_schema=False)
def host_console_page(request: Request):
    """Serve the host console.

    The PRD gives the host a native app; this browser console exists because that app
    has no room screen yet, leaving no way at all to add a source mid-salon (FR3) or
    generate an invitation. It authenticates with the same email OTP as the app, so it
    grants nothing the host does not already have.
    """
    return _page(request, "host.html")


@router.get("/", include_in_schema=False)
@router.get("/call", include_in_schema=False)
def landing_page(request: Request):
    """The front door: place a call at the top, watch the desk below.

    Both sides of the hotel scenario on one page, because they only make sense together — a
    caller with nobody reading, or a desk with nobody calling, each looks like half a product.

    The call is real. There is no SIP trunk and no dispatch rule, so nobody can dial a Salon
    today; this is the same door opened from a browser, and it goes through the same six-digit
    code, the same pool and the same invitation a telephone will use.

    The desk joins the Salon for real and offers nothing to press. Read-only is about the
    controls, not the presence: the clerk is in the room and hearing it, the captions arrive on
    the same data channel the console reads, and no microphone is ever enabled. Answering
    happens in the console — a panel that looked like it could answer would be the worst kind
    of lie in front of somebody with a caller waiting.

    Two paths for one page: / is where somebody arrives, /call is what a host writes down for
    a guest to type. Serving the same file rather than redirecting keeps them the same page
    rather than two that drift.
    """
    return _page(request, "index.html")


@router.get("/report", include_in_schema=False)
def participant_report_page(request: Request):
    """Serve the participant report console.

    The page is public; what it shows is not. Everything on it arrives from /admin/report,
    which requires a token belonging to an address in admin_emails — one address today. So
    this serves an empty shell to anybody and its contents to one person, which is the right
    split: a page that refused to load at all would need its own gate, duplicating the one
    the API already applies to the data.
    """
    return _page(request, "report.html")


# The pages whose dictionaries can be requested, and the languages that exist as generated
# files. Allowlists rather than a constructed path: `../../secret` in a language name would
# otherwise serve any file in the container, and a check for ".." is the kind of guard that
# gets subtly wrong. Nothing outside these two sets can be named at all.
_I18N_PAGES = frozenset({"host", "join"})
_I18N_LANGUAGES = frozenset(
    {
        "es", "pt", "de", "it", "ar", "fa", "bn", "zh", "hi", "id", "ja", "ko",
        "ru", "tr", "vi", "af", "am", "az", "bg", "bs", "ca", "cs", "cy", "da",
        "el", "et", "fi", "ga", "gu", "ha", "he", "hr", "ht", "hu", "hy", "is",
        "ka", "kk", "kn", "lt", "lv", "mk", "ml", "mn", "mr", "ms", "mt", "nl",
        "no", "pa", "pl", "ps", "ro", "si", "sk", "sl", "so", "sq", "sr", "sv",
        "sw", "ta", "te", "th", "tl", "uk", "ur", "uz",
    }
)


@router.get("/i18n/{page}/{language}", include_in_schema=False)
def interface_dictionary(page: str, language: str):
    """The interface strings for one page in one language.

    English and French are written by hand inside the pages themselves, so they are never
    requested here — they must render with no network involved. These fourteen are
    generated from the English by Amazon Translate and fetched on demand: shipping sixteen
    dictionaries inline would triple two files that are already long, and a reader who
    never leaves English would download fifteen they will not use.

    404 rather than 500 for an unknown pair. A language that has not been generated yet is
    a missing file, not a broken request, and the client falls back to English.
    """
    if page not in _I18N_PAGES or language not in _I18N_LANGUAGES:
        raise HTTPException(status_code=404, detail="Dictionary not found.")

    path = os.path.join(_WEB_DIR, "i18n", f"{page}.{language}.json")
    if not os.path.isfile(path):
        raise HTTPException(status_code=404, detail="Dictionary not found.")

    return FileResponse(
        path,
        media_type="application/json",
        # Regenerated only when the English changes, which is a deploy. An hour of caching
        # spares every reader in a non-primary language a request per page load.
        headers={"Cache-Control": "public, max-age=3600"},
    )


@router.get("/voice-languages", include_in_schema=False)
def voice_languages():
    """The languages a Salon's agent can be told to speak.

    Served rather than written into the page so the menu and the validator cannot disagree.
    A page holding its own copy would offer a language the API rejects, and the caller would
    press call and be refused for a reason nothing on screen could explain.

    `documented` marks the twenty xAI publishes, as opposed to the ones added because the model
    was tried in them. Nothing in the interface uses it yet; it is here so that the distinction
    reaches whoever eventually wants to show it, rather than being flattened on the way out.
    """
    return {
        "languages": [
            {
                "tag": tag,
                "label": label,
                "documented": tag in voice_languages_service.DOCUMENTED_TAGS,
            }
            for tag, label in voice_languages_service.VOICE_LANGUAGES
        ]
    }
